#!/usr/bin/env bash
# Build docs/db/demo-database.sql: the whole database WITH demo data
# (10 restaurants, 10 guests, a month of visits, bookings and reviews).
# Load it into an EMPTY database instead of schema.sql to get a ready demo.
#
# It migrates a temporary empty database, runs scripts/seed-demo.ts on it and
# dumps everything. The dump creates tables, loads data, then adds triggers,
# so the append-only guards on money tables are in place afterwards.
#   npm run db:export-demo
# ADMIN_URL: a role allowed to create databases (default: local spot role).
set -euo pipefail
cd "$(dirname "$0")/.."

ADMIN_URL="${ADMIN_URL:-postgresql://spot:spot@localhost:5432/postgres}"
TEMP_DB="spot_demo_export"
TEMP_URL="${ADMIN_URL%/*}/${TEMP_DB}"
OUT="docs/db/demo-database.sql"

psql "$ADMIN_URL" -qX -v ON_ERROR_STOP=1 \
  -c "DROP DATABASE IF EXISTS ${TEMP_DB}" -c "CREATE DATABASE ${TEMP_DB}"
trap 'psql "$ADMIN_URL" -qX -c "DROP DATABASE IF EXISTS ${TEMP_DB}" >/dev/null' EXIT

env -u VERCEL_ENV DATABASE_URL="$TEMP_URL" node scripts/migrate.mjs >/dev/null
env -u VERCEL_ENV DATABASE_URL="$TEMP_URL" LOG_LEVEL=warn npm run --silent db:seed-demo

LAST=$(ls drizzle/*.sql | tail -1 | xargs basename)
{
  echo "-- Spot DEMO database (schema + demo data) — generated by scripts/export-demo-db.sh"
  echo "-- Up to migration: ${LAST}. Every demo login uses the password demo1234."
  echo "-- Load into an EMPTY database (see docs/db/README.md). Never use it for real customers."
  echo
  # \restrict lines are psql-only; drop them so GUI tools can run the file too.
  pg_dump --inserts --no-owner --no-privileges --no-comments "$TEMP_URL" \
    | grep -vE '^\\(un)?restrict ' | grep -v '^-- Dumped '
} > "$OUT"

echo "Wrote ${OUT} (up to ${LAST})."
