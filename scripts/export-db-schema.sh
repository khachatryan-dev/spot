#!/usr/bin/env bash
# Rebuild docs/db/schema.sql: the full database (tables, indexes, triggers,
# functions) as plain SQL that any PostgreSQL 15+ tool can run, plus the
# migration journal so the app knows every migration is already applied.
#
# It migrates a temporary, empty database and dumps that, so the file always
# matches drizzle/ exactly. Run after adding a migration:
#   npm run db:export-schema
# ADMIN_URL: a role allowed to create databases (default: local spot role).
set -euo pipefail
cd "$(dirname "$0")/.."

ADMIN_URL="${ADMIN_URL:-postgresql://spot:spot@localhost:5432/postgres}"
TEMP_DB="spot_schema_export"
TEMP_URL="${ADMIN_URL%/*}/${TEMP_DB}"
OUT="docs/db/schema.sql"

psql "$ADMIN_URL" -qX -v ON_ERROR_STOP=1 \
  -c "DROP DATABASE IF EXISTS ${TEMP_DB}" -c "CREATE DATABASE ${TEMP_DB}"
trap 'psql "$ADMIN_URL" -qX -c "DROP DATABASE IF EXISTS ${TEMP_DB}" >/dev/null' EXIT

env -u VERCEL_ENV DATABASE_URL="$TEMP_URL" node scripts/migrate.mjs >/dev/null

LAST=$(ls drizzle/*.sql | tail -1 | xargs basename)
{
  echo "-- Spot database schema — generated by scripts/export-db-schema.sh"
  echo "-- Up to migration: ${LAST}"
  echo "-- Load into an EMPTY database (see docs/db/README.md). Do not edit by hand."
  echo
  # \restrict lines are psql-only; drop them so GUI tools can run the file too.
  pg_dump --schema-only --no-owner --no-privileges --no-comments "$TEMP_URL" \
    | grep -vE '^\\(un)?restrict ' | grep -v '^-- Dumped '
  echo
  echo "-- Migration journal: tells the app these migrations are already applied."
  pg_dump --data-only --inserts --no-owner --no-privileges \
    --table=drizzle.__drizzle_migrations "$TEMP_URL" \
    | grep -E '^(INSERT|SELECT pg_catalog.setval)'
} > "$OUT"

echo "Wrote ${OUT} (up to ${LAST})."
