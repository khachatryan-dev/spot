/**
 * URL-safe slug matching the DB check `^[a-z0-9]+(-[a-z0-9]+)*$`.
 * Armenian is transliterated, other accents stripped. May return "".
 */
export function slugify(input: string, maxLength = 60): string {
  const lower = input.toLowerCase().replace(/ու/g, "u");
  const transliterated = [...lower].map((char) => ARMENIAN[char] ?? char).join("");
  return transliterated
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, maxLength)
    .replace(/-+$/g, "");
}
