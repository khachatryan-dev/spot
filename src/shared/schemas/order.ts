import { z } from "zod";

import { MAX_ITEM_QUANTITY } from "@/shared/domain/item-selection";

export const MAX_ORDER_LINES = 50;
export const MAX_LINE_NOTE = 200;
export const MAX_ORDER_NOTE = 500;

/**
 * What a guest sends to place an order (§16). Deliberately no prices or
 * names: the server takes those from the database. Unknown fields (e.g. a
 * tampered "price") are stripped.
 */
export const orderLineSchema = z.object({
  itemId: z.uuid(),
  modifierIds: z.array(z.uuid()).max(30).default([]),
  quantity: z
    .number()
    .int("quantityInvalid")
    .min(1, "quantityInvalid")
    .max(MAX_ITEM_QUANTITY, "quantityInvalid"),
  note: z.string().trim().max(MAX_LINE_NOTE, "noteTooLong").default(""),
});

export const orderRequestSchema = z.object({
  lines: z.array(orderLineSchema).min(1, "orderEmpty").max(MAX_ORDER_LINES, "tooManyLines"),
  note: z.string().trim().max(MAX_ORDER_NOTE, "noteTooLong").default(""),
  /** Generated by the browser once per checkout; retries reuse it. */
  idempotencyKey: z.string().min(8).max(100),
});

export type OrderLineInput = z.input<typeof orderLineSchema>;
export type OrderRequest = z.input<typeof orderRequestSchema>;
export type ParsedOrderRequest = z.output<typeof orderRequestSchema>;
